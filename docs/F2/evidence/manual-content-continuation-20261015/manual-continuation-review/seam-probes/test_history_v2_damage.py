"""Two actual six-goal receipts, then isolated in-memory history damage.

Expected refusals are literal, not generated by a product validator. No damaged
history is written into PostgreSQL. Full coordinated trusted-admin rewriting of
all historical records is outside these checksum/link integrity probes.
"""
from copy import deepcopy
from pathlib import Path
from uuid import uuid4
import hashlib
import json
import os
import pytest
from parkweave import service_case_steps as service
from parkweave.store import Conflict
from test_plan_source_conflicts import (
    http_f, link_fixture, receipt_fixture, preparation_fixture,
    read, edit, changed, path, snapshot, complete,
)
from test_preparation import headers
from test_final_unknown import SIX_GOALS

HERE = Path(__file__).resolve().parent


def sha(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def text_sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def change_at(event, field_path, value):
    target = event
    for key in field_path[:-1]:
        target = target[key]
    target[field_path[-1]] = value


def rehash(parent, event, ledger_event, mirror=True):
    proof = event['plan_note']
    proof['preview_sha256'] = sha(proof['preview_basis'])
    proof['request']['expected_preview_sha256'] = proof['preview_sha256']
    event['fingerprint'] = sha(dict(preparation_id=str(parent['id']), **proof['request']))
    proof['sha256'] = sha({k: v for k, v in proof.items() if k != 'sha256'})
    if mirror:
        ledger_event['payload']['plan_event'] = deepcopy(event)
        ledger_event['fingerprint'] = event['fingerprint']
        ledger_event['sha256'] = sha({k: v for k, v in ledger_event.items() if k != 'sha256'})
        parent['service_case_plan']['owner_amendments'][event['step_id']] = deepcopy(proof['after_note'])


@pytest.mark.parametrize('action', ['KEEP_AND_CONTINUE', 'MERGE_NOTE'])
def test_actual_receipt_v2_history_refuses_literal_damage_matrix(http_f, action):
    f = http_f
    parent_ref, _, _, _ = complete(f, goals=SIX_GOALS, local=True)
    incoming = 'SYNTHETIC literal requirement A\nSYNTHETIC literal requirement B'
    manual = 'SYNTHETIC retained owner note\n' + incoming
    edit(f, parent_ref, manual)
    parent_ref, card = changed(f, parent_ref, mixed=True, text=incoming)
    view = read(f, parent_ref, card).json()
    body = deepcopy(view['action_requests'][action])
    body['reason'] = 'SYNTHETIC actual v2 history probe baseline'
    if action == 'MERGE_NOTE':
        body['text'] = manual + '\nSYNTHETIC explicit merged reminder'
    response = f[3].post(path(parent_ref) + '/commands', headers=headers(f[2], key=uuid4().hex), json=body)
    assert response.status_code == 200, response.text
    with f[1].connect() as connection:
        pristine = connection.execute('SELECT * FROM preparations WHERE id=%s', (parent_ref['preparation_id'],)).fetchone()
    assert pristine['service_case_plan']['required_goals'] == SIX_GOALS
    assert service._recovery_proofs(pristine)
    unchanged = snapshot(f)
    mutations = [
        ('proof_version_bool', ['plan_note', 'version'], True),
        ('unknown_proof_version', ['plan_note', 'version'], 3),
        ('basis_schema_bool', ['plan_note', 'preview_basis', 'schema'], True),
        ('basis_wrong_schema', ['plan_note', 'preview_basis', 'schema'], 1),
        ('snapshot_schema_bool', ['plan_note', 'preview_basis', 'continuation', 'schema'], True),
        ('baseline_wrong_id', ['plan_note', 'preview_basis', 'continuation', 'baseline', 'id'], str(uuid4())),
        ('baseline_epoch_wrong_type', ['plan_note', 'preview_basis', 'continuation', 'baseline_epoch'], 1),
        ('baseline_epoch_mismatched', ['plan_note', 'preview_basis', 'continuation', 'baseline_epoch'], '99999999999999999999'),
        ('old_package_epoch_ref_wrong_slot', ['plan_note', 'preview_basis', 'continuation', 'baseline_package_epochs', 0, 'slot'], 'wrong_slot'),
        ('old_package_epoch_hash_mismatch', ['plan_note', 'preview_basis', 'continuation', 'baseline_package_epochs_sha256'], '0' * 64),
        ('condition_count_mismatch', ['plan_note', 'preview_basis', 'continuation', 'conditions', 0, 'required_count'], 2),
        ('condition_line_mismatch', ['plan_note', 'preview_basis', 'continuation', 'conditions', 0, 'line'], 'SYNTHETIC forged line'),
        ('condition_id_mismatch', ['plan_note', 'preview_basis', 'continuation', 'conditions', 0, 'id'], '1' * 64),
        ('fake_semantic_satisfied', ['plan_note', 'preview_basis', 'continuation', 'semantic_evaluated'], True),
        ('manual_preserved_false', ['plan_note', 'preview_basis', 'continuation', 'manual_preserved'], False),
        ('manual_revision_mismatch', ['plan_note', 'preview_basis', 'continuation', 'manual', 'revision'], 63),
        ('after_forged_source_origin', ['plan_note', 'after_note', 'origin'], 'SOURCE'),
        ('after_forged_verified_package', ['plan_note', 'after_note', 'verified_package_sha256'], '2' * 64),
        ('source_epoch_not_hash', ['plan_note', 'preview_basis', 'source_epochs_sha256'], 'NOT_A_HASH'),
        ('old_package_only_one_slot', ['plan_note', 'preview_basis', 'continuation', 'baseline_package_epochs'], []),
    ]
    results = []
    for label, fields, value in mutations:
        parent = deepcopy(pristine)
        event = parent['service_case_plan']['events'][-1]
        ledger_event = parent['opportunities']['events'][-1]
        change_at(event, fields, value)
        rehash(parent, event, ledger_event)
        with pytest.raises(Conflict):
            service._recovery_proofs(parent)
        results.append(dict(case=label, refusal='Conflict', both_sides_checksum_recomputed=True))

    for label, side in [('one_sided_plan_rehashed', 'plan'), ('one_sided_ledger_rehashed', 'ledger')]:
        parent = deepcopy(pristine)
        original = parent['service_case_plan']['events'][-1]
        ledger_event = parent['opportunities']['events'][-1]
        event = original if side == 'plan' else ledger_event['payload']['plan_event']
        event['plan_note']['request']['reason'] = 'SYNTHETIC single side rewrite'
        event['reason'] = event['plan_note']['request']['reason']
        rehash(parent, event, ledger_event, mirror=False)
        if side == 'ledger':
            ledger_event['fingerprint'] = event['fingerprint']
            ledger_event['sha256'] = sha({k: v for k, v in ledger_event.items() if k != 'sha256'})
        with pytest.raises(Conflict):
            service._recovery_proofs(parent)
        results.append(dict(case=label, refusal='Conflict', changed_side=side))

    # Hash-consistent candidate text must still satisfy the independent manual
    # preservation and exact source-line constraints, not only byte checksums.
    for label, replacement in [('drop_all_source_conditions', 'SYNTHETIC retained owner note'),
                               ('drop_original_M_while_keep_all_S', incoming)]:
        parent = deepcopy(pristine)
        event = parent['service_case_plan']['events'][-1]
        ledger_event = parent['opportunities']['events'][-1]
        event['plan_note']['after_note']['text'] = replacement
        event['plan_note']['after_note']['text_sha256'] = text_sha(replacement)
        if action == 'MERGE_NOTE':
            event['plan_note']['request']['text'] = replacement
        rehash(parent, event, ledger_event)
        with pytest.raises(Conflict):
            service._recovery_proofs(parent)
        results.append(dict(case=label, refusal='Conflict', both_sides_checksum_recomputed=True))

    assert snapshot(f) == unchanged
    result = dict(action=action, actual_success_receipt=True, proof_version=2,
                  original_six_goals=True, isolated_in_memory_damage=True,
                  no_damaged_history_written_to_PG=True, product_business_rows_unchanged=True,
                  damaged_cases=len(results), all_refused=True, cases=results,
                  actual_API_PG_setup=True, full_coordinated_trusted_admin_history_rewrite_claimed=False)
    with (HERE / (os.environ['REVIEW_SEAM_WINDOW'] + '-history-observed.jsonl')).open('a') as stream:
        stream.write(json.dumps(result, sort_keys=True) + '\n')
